PREFIX = "ratatoskr.skaldhall.io/"


def server_config():
    return ("port 1194\nproto udp4\ndev tun0\ntopology subnet\n"
            "server 10.88.0.0 255.255.255.0\n"
            "ca /etc/synthetic/ca.crt\ncert /etc/synthetic/server.crt\n"
            "key /etc/synthetic/server.key\ndh none\n"
            "tls-version-min 1.2\nremote-cert-tls client\n"
            "data-ciphers AES-256-GCM:AES-128-GCM\nauth SHA256\n"
            "keepalive 5 20\npersist-key\npersist-tun\n")


def client_config(remote, ca, cert, key):
    # Only caller-chosen Kubernetes Service DNS is interpolated; no arbitrary
    # OpenVPN options, routes or executable scripts enter this profile.
    if not remote.endswith(".svc.cluster.local") or not all(
            part and len(part) <= 63 and all(c.islower() or c.isdigit() or c == "-" for c in part)
            and part[0].isalnum() and part[-1].isalnum() for part in remote.split(".")[:2]):
        raise ValueError("invalid service DNS")
    return (f"client\nproto udp4\nremote {remote} 1194\nnobind\n"
            "remote-cert-tls server\nverify-x509-name synthetic-server name\n"
            "tls-version-min 1.2\ndata-ciphers AES-256-GCM:AES-128-GCM\n"
            + "".join(f"<{name}>\n{content.rstrip()}\n</{name}>\n" for name, content in
                      (("ca", ca), ("cert", cert), ("key", key))))


def generate_pki(folder):
    def run(*args):
        subprocess.run(["openssl", *map(str, args)], cwd=folder, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=25)

    # Ephemeral 2048-bit RSA keys; serial database and config stay private.
    run("req", "-x509", "-newkey", "rsa:2048", "-sha256", "-nodes", "-days", "1",
        "-subj", "/CN=synthetic-ca", "-keyout", "ca.key", "-out", "ca.crt")
    for role, eku in (("server", "serverAuth"), ("client", "clientAuth")):
        run("req", "-newkey", "rsa:2048", "-sha256", "-nodes", "-subj",
            f"/CN=synthetic-{role}", "-keyout", f"{role}.key", "-out", f"{role}.csr")
        ext = folder / f"{role}.ext"
        ext.write_text(f"basicConstraints=CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\n"
                       f"extendedKeyUsage={eku}\n")
        run("x509", "-req", "-in", f"{role}.csr", "-CA", "ca.crt", "-CAkey", "ca.key",
            "-CAcreateserial", "-days", "1", "-sha256", "-extfile", ext,
            "-out", f"{role}.crt")


def secret(namespace, name, data):
    return {"apiVersion": "v1", "kind": "Secret", "metadata": {"name": name, "namespace": namespace},
            "type": "Opaque", "data": {k: base64.b64encode(v.encode()).decode() for k, v in data.items()}}


