def _bounded(argv, *, payload=None, timeout, max_output):
    """Drain only a capped stdout pipe; stderr discarded, timeout kills group."""
    process = None
    selector = selectors.DefaultSelector()
    output = bytearray()
    try:
        process = subprocess.Popen(argv, stdin=subprocess.PIPE if payload is not None else subprocess.DEVNULL,
                                   stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=_env(),
                                   start_new_session=True)
        selector.register(process.stdout, selectors.EVENT_READ)
        sent = 0
        if payload is not None:
            os.set_blocking(process.stdin.fileno(), False)
            selector.register(process.stdin, selectors.EVENT_WRITE)
        end = time.monotonic() + timeout
        while selector.get_map():
            remaining = end - time.monotonic()
            if remaining <= 0:
                raise AdapterError("Bounded Kubernetes operation timed out.")
            for key, _ in selector.select(remaining):
                if key.fileobj == process.stdin:
                    try:
                        sent += os.write(process.stdin.fileno(), payload[sent:sent + 4096])
                    except BrokenPipeError:
                        raise AdapterError("Kubernetes stdin closed before fixture transfer.") from None
                    if sent == len(payload):
                        selector.unregister(process.stdin)
                        process.stdin.close()
                    continue
                chunk = os.read(key.fileobj.fileno(), min(4096, max_output + 1 - len(output)))
                if chunk:
                    output.extend(chunk)
                    if len(output) > max_output:
                        raise AdapterError("Bounded Kubernetes output exceeded limit.")
                else:
                    selector.unregister(key.fileobj)
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise AdapterError("Bounded Kubernetes operation timed out.")
        if process.wait(timeout=remaining) != 0:
            raise AdapterError("Kubernetes operation failed (details suppressed).")
        return bytes(output)
    except (OSError, ValueError, subprocess.TimeoutExpired, BrokenPipeError):
        raise AdapterError("Bounded Kubernetes operation unavailable or failed.") from None
    finally:
        selector.close()
        if process is not None:
            # Kill an isolated process group even if kubectl exited but a
            # descendant inherited stdout and kept the pipe open.
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            try:
                process.wait(timeout=1)
            except subprocess.TimeoutExpired:
                raise AdapterError("Local kubectl child could not be reaped.") from None
            if process.stdin:
                process.stdin.close()
            if process.stdout:
                process.stdout.close()


class FixtureAPI:
    def __init__(self, owner, transport=_bounded):
        if not isinstance(owner, lifecycle.Lifecycle) or owner.deadline is None or owner.closed:
            raise AdapterError("A running, authorized Lifecycle is required.")
        self.owner, self.transport = owner, transport
        self.exit_health_uid = None
        self.create_attempts = set()  # never retry an ambiguous remote POST
        self.created = {}             # only server-returned immutable UIDs

    def _time(self):
        if self.owner.closed:
            raise AdapterError("Lifecycle is closed.")
        try:
            return self.owner._time(self.owner.deadline)
        except lifecycle.LifecycleError:
            raise AdapterError("Final-gate total deadline exceeded.") from None

    def _namespace(self, name):
        if name not in self.owner.names or name not in self.owner.owned:
            raise AdapterError("Namespace is not confirmed owned by this Lifecycle.")
        try:
            observed = self.owner.api.get(name, timeout=self._time())
            self.owner._record(name, observed)
        except (lifecycle.LifecycleError, KeyError, TypeError, AttributeError):
            raise AdapterError("Namespace UID/ownership recheck failed.") from None
        if self.owner.owned[name] != observed["metadata"]["uid"]:
            raise AdapterError("Namespace UID changed.")
        return name

    def _call(self, args, *, payload=None, max_output=262144):
        timeout = self._time()
        argv = ["kubectl", "--context", CONTEXT, "--request-timeout=10s", *args]
        try:
            result = self.transport(argv, payload=payload, timeout=timeout, max_output=max_output)
            if not isinstance(result, bytes) or len(result) > max_output:
                raise AdapterError("Kubernetes output violated limit or type contract.")
            if self.owner.clock() >= self.owner.deadline:
                raise AdapterError("Final-gate total deadline exceeded.")
            return result
        except (KeyboardInterrupt, SystemExit, lifecycle.Interrupted):
            raise
        except BaseException:
            raise AdapterError("Kubernetes transport failed (details suppressed).") from None

    @staticmethod
    def _name(kind, name):
        allowed = RESOURCES.get(kind)
        if ((allowed is None and kind not in RESOURCES) or not isinstance(name, str) or
                (allowed is not None and name not in allowed) or
                (allowed is None and (not GENERATED.fullmatch(name) or ".." in name))):
            raise AdapterError("Resource kind or name not allowlisted.")

    def get(self, kind, name, namespace):
        self._name(kind, name)
        self._namespace(namespace)
        raw = self._call(["get", kind, name, "--namespace", namespace, "-o", "json"])
        try:
            obj = json.loads(raw)
            if obj.get("metadata", {}).get("name") != name or obj["metadata"].get("namespace") != namespace:
                raise ValueError()
            return obj
        except (ValueError, KeyError, AttributeError, TypeError):
            raise AdapterError("Kubernetes object identity or JSON malformed.") from None

    def create(self, obj):
        """Single POST with pinned server-returned UID; no name-only adoption.

        The attempted name is quarantined BEFORE transport. A timeout, lost
        response, identity mismatch or malformed Secret response is ambiguous:
        only Lifecycle namespace deletion may clean it, never a guessed GET.
        """
        try:
            kind, meta = obj["kind"], obj["metadata"]
            name, namespace = meta["name"], meta["namespace"]
            if kind not in CREATE or name not in FIXTURE[kind] or type(obj) is not dict:
                raise ValueError()
            if namespace != (self.owner.names[1] if kind == "EgressPolicy" or
                             kind == "Pod" and (name == "synthetic-client" or
                                                  name.startswith("synthetic-probe-")) else self.owner.names[0]):
                raise ValueError()
            if kind == "ConfigMap":
                if (set(obj) != {"apiVersion", "kind", "metadata", "data"} or
                        obj.get("apiVersion") != "v1" or
                        obj.get("data") != {"exit-enabled": "true"} or
                        set(meta) != {"name", "namespace", "labels"} or
                        meta.get("labels") != {lifecycle.LABEL: self.owner.token}):
                    raise ValueError()
            if kind == "Pod" and name.startswith("synthetic-probe-"):
                try:
                    from . import prepare
                except ImportError:
                    import prepare
                expected = prepare.selected_probe_pod(self.owner.names[1], self.owner.names[0],
                                                      name.removeprefix("synthetic-probe-"),
                                                      obj["spec"]["containers"][0]["args"][1])
                if obj != expected:
                    raise ValueError()
            if kind == "Secret":
                keys = {"ca.crt", "server.crt", "server.key", "server.conf"} if name == "synthetic-server" else {"client.ovpn"}
                if (obj.get("apiVersion") != "v1" or obj.get("type") != "Opaque" or
                        set(obj.get("data", {})) != keys or
                        set(obj) != {"apiVersion", "kind", "metadata", "type", "data"} or
                        set(meta) != {"name", "namespace"}):
                    raise ValueError()
            self._namespace(namespace)
            payload = json.dumps(obj, separators=(",", ":"), allow_nan=False).encode()
            if len(payload) > 65536:
                raise ValueError()
        except (KeyError, TypeError, ValueError, AttributeError, IndexError):
            raise AdapterError("Fixture kind, namespace or payload not allowlisted.") from None
        identity = (kind, namespace, name)
        if identity in self.create_attempts:
            raise AdapterError("Fixture CREATE already attempted; no duplicate or ambiguous retry.")
        self.create_attempts.add(identity)
        # A fixed kubectl JSONPath outputs ONLY identity, never Secret.data.
        # Backend receives a complete response, but private bytes do not pass
        # through subprocess stdout/capture or later Python parsing.
        raw = self._call(["create", "-f", "-", "-o", CREATE_IDENTITY], payload=payload,
                         max_output=256)
        try:
            fields = raw.decode("ascii").rstrip("\n").split("\t")
            if (len(fields) != 5 or fields[:4] != [obj["apiVersion"], kind, namespace, name] or
                    not UID.fullmatch(fields[4])):
                raise ValueError()
            uid = fields[4]
        except (UnicodeError, ValueError, TypeError):
            raise AdapterError("Fixture CREATE response identity/UID unverified; no retry permitted.") from None
        self._namespace(namespace)
        self.created[identity] = uid
        return {"kind": kind, "namespace": namespace, "name": name, "uid": uid}

    def _exit_health(self, expected_uid=None):
        """Never inspect unrelated ConfigMaps or return arbitrary ConfigMap data."""
        config = self.get("configmap", "synthetic-exit-health", self.owner.names[0])
        meta = config.get("metadata", {})
        uid, version = meta.get("uid"), meta.get("resourceVersion")
        if (config.get("apiVersion") != "v1" or config.get("kind") != "ConfigMap" or
                set(config) != {"apiVersion", "kind", "metadata", "data"} or
                meta.get("namespace") != self.owner.names[0] or
                meta.get("labels") != {lifecycle.LABEL: self.owner.token} or
                meta.get("deletionTimestamp") or
                not isinstance(uid, str) or not UID.fullmatch(uid) or
                not isinstance(version, str) or not re.fullmatch(r"[0-9]{1,32}", version) or
                config.get("data") not in ({"exit-enabled": "true"}, {"exit-enabled": "false"}) or
                (expected_uid is not None and uid != expected_uid)):
            raise AdapterError("Probe-only ConfigMap identity or contents invalid.")
        return uid, version, config["data"]["exit-enabled"]

    def exit_health_snapshot(self):
        uid, version, state = self._exit_health(self.exit_health_uid)
        if self.exit_health_uid is None:
            if state != "true":
                raise AdapterError("Probe-only ConfigMap must start enabled.")
            self.exit_health_uid = uid
        return uid, version, state

    def _replace_exit_health(self, uid, version, enabled):
        if (uid != self.exit_health_uid or not isinstance(version, str) or
                not re.fullmatch(r"[0-9]{1,32}", version) or type(enabled) is not bool):
            raise AdapterError("Probe-only update missing pinned UID/version/state.")
        observed_uid, observed_version, _ = self._exit_health(uid)
        if observed_version != version or observed_uid != uid:
            raise AdapterError("Probe-only ConfigMap resourceVersion changed; refusing overwrite.")
        namespace = self.owner.names[0]
        obj = {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {
            "name": "synthetic-exit-health", "namespace": namespace,
            "uid": uid, "resourceVersion": version,
            "labels": {lifecycle.LABEL: self.owner.token}},
            "data": {"exit-enabled": "true" if enabled else "false"}}
        # A complete object through stdin; no patches or loggable command
        # values. API server's resourceVersion update is the atomic CAS.
        payload = json.dumps(obj, separators=(",", ":")).encode()
        raw = self._call(["replace", "--raw=/api/v1/namespaces/" + namespace +
                          "/configmaps/synthetic-exit-health", "-f", "-"],
                         payload=payload, max_output=4096)
        try:
            updated = json.loads(raw)
            meta = updated["metadata"]
            if (updated.get("kind") != "ConfigMap" or
                    meta.get("name") != "synthetic-exit-health" or
                    meta.get("namespace") != namespace or meta.get("uid") != uid or
                    not isinstance(meta.get("resourceVersion"), str) or
                    not re.fullmatch(r"[0-9]{1,32}", meta["resourceVersion"]) or
                    meta["resourceVersion"] == version or
                    meta.get("labels") != {lifecycle.LABEL: self.owner.token} or
                    updated.get("data") != obj["data"]):
                raise ValueError()
        except (ValueError, TypeError, KeyError, AttributeError):
            raise AdapterError("Probe-only ConfigMap update response malformed.") from None
        rechecked_uid, rechecked_version, state = self._exit_health(uid)
        if (rechecked_uid != uid or rechecked_version != meta["resourceVersion"] or
                state != obj["data"]["exit-enabled"]):
            raise AdapterError("Probe-only ConfigMap update confirmation failed.")
        return rechecked_version

    @contextmanager
    def exit_health_outage(self):
        """Bounded, best-effort restore; any error forbids PASS and Lifecycle
        still removes the owned namespace. No server Pod exec or signal.
        """
        if self.owner.deadline - self.owner.clock() < 60:
            raise AdapterError("Insufficient final-gate time to reserve probe restoration.")
        uid, version, state = self.exit_health_snapshot()
        if state != "true":
            raise AdapterError("Probe-only health switch not initially enabled.")
        disabled_version = None
        try:
            disabled_version = self._replace_exit_health(uid, version, False)
            yield uid
        finally:
            try:
                # A timed-out update might have reached the API. Re-read the
                # pinned object before restoration; never overwrite a foreign
                # UID, changed labels, or unknown state/version. If the disable
                # succeeded, an intervening writer must not be silently adopted.
                current_uid, current_version, current_state = self._exit_health(uid)
                if disabled_version is not None and current_version != disabled_version:
                    raise AdapterError("Probe-only ConfigMap changed during outage; refusing overwrite.")
                if current_state == "false":
                    self._replace_exit_health(current_uid, current_version, True)
                elif current_state != "true" or disabled_version is not None:
                    raise AdapterError("Probe-only restoration state invalid.")
            except (KeyboardInterrupt, SystemExit, lifecycle.Interrupted):
                raise
            except BaseException:
                raise AdapterError("Probe-only ConfigMap restoration unverified; no PASS permitted.") from None

