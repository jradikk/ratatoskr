    def pod_image_id(self, namespace, name, container, uid):
        if (name, container, namespace) not in {
                ("synthetic-client", "client", self.owner.names[1]),
                ("synthetic-vpn", "server", self.owner.names[0]),
                ("synthetic-witness", "witness", self.owner.names[0])}:
            raise AdapterError("Pod image target not allowlisted.")
        if not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Pod UID required for image check.")
        pod = self.get("pod", name, namespace)
        if pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp"):
            raise AdapterError("Pod UID changed or deletion started.")
        statuses = [s for s in pod.get("status", {}).get("containerStatuses", []) if s.get("name") == container]
        if len(statuses) != 1 or statuses[0].get("ready") is not True:
            raise AdapterError("Pod container not Ready.")
        image_id = statuses[0].get("imageID")
        if not isinstance(image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", image_id):
            raise AdapterError("Pod runtime image ID malformed or mutable.")
        return image_id

    def server_session(self, namespace, uid, *, expected_image_id):
        """Only sanitized status reader in exact server Pod; never cat/raw logs.

        Caller MUST treat JSON as private transient evidence, never persist it.
        Like kubectl exec generally, there is no server-side Pod UID compare;
        a replacement between precheck and exec remains a hard full-gate block.
        """
        if namespace != self.owner.names[0] or not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Server session namespace or Pod UID invalid.")
        if not isinstance(expected_image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", expected_image_id):
            raise AdapterError("Expected immutable server runtime image required.")
        self._namespace(namespace)
        pod = self.get("pod", "synthetic-vpn", namespace)
        if (pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp") or
                not pod.get("spec", {}).get("nodeName")):
            raise AdapterError("Server Pod UID, scheduling or deletion invalid.")
        spec = [c for c in pod.get("spec", {}).get("containers", []) if c.get("name") == "server"]
        status = [c for c in pod.get("status", {}).get("containerStatuses", []) if c.get("name") == "server"]
        if (len(spec) != 1 or len(status) != 1 or spec[0].get("imagePullPolicy") != "Never" or
                status[0].get("ready") is not True or status[0].get("imageID") != expected_image_id):
            raise AdapterError("Server container not Ready with expected immutable runtime image.")
        raw = self._call(["--namespace", namespace, "exec", "synthetic-vpn", "-c", "server", "--",
                          *SERVER_COMMAND], max_output=768)
        self._namespace(namespace)
        if pod["metadata"].get("uid") != self.get("pod", "synthetic-vpn", namespace)["metadata"].get("uid"):
            raise AdapterError("Server Pod UID changed during session read.")
        try:
            session = json.loads(raw)
            if not isinstance(session, dict) or set(session) != {"sessions"} or not isinstance(session["sessions"], list) or len(session["sessions"]) not in (1, 2):
                raise ValueError()
            names = []
            ips = []
            for entry in session["sessions"]:
                if (not isinstance(entry, dict) or
                        set(entry) != {"cn", "virtualIPv4", "received", "sent", "connected", "peer", "cipher"} or
                        entry.get("cn") not in {"synthetic-client", "synthetic-witness"} or
                        entry.get("cipher") not in {"AES-256-GCM", "AES-128-GCM"} or
                        any(type(entry.get(key)) is not int or entry[key] < 0 for key in ("received", "sent", "connected", "peer")) or
                        not isinstance(entry.get("virtualIPv4"), str) or
                        not re.fullmatch(r"10\.88\.0\.[0-9]{1,3}", entry["virtualIPv4"])):
                    raise ValueError()
                names.append(entry["cn"])
                ips.append(entry["virtualIPv4"])
            if len(set(names)) != len(names) or len(set(ips)) != len(ips) or names[0] != "synthetic-client":
                raise ValueError()
            return session
        except (ValueError, UnicodeError, TypeError, AttributeError):
            raise AdapterError("Sanitized server session output malformed.") from None

    def exec(self, namespace, name, uid, container, command, *, expected_image_id):
        if (name, container) != ("synthetic-client", "client") or namespace != self.owner.names[1]:
            raise AdapterError("Exec Pod/container/namespace not allowlisted.")
        if command not in COMMANDS or not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Exec command or Pod UID not allowlisted.")
        if not isinstance(expected_image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", expected_image_id):
            raise AdapterError("Expected immutable runtime image ID required before exec.")
        pod = self.get("pod", name, namespace)
        if (pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp") or
                not pod.get("spec", {}).get("nodeName")):
            raise AdapterError("Exec Pod UID changed, unscheduled or deletion started.")
        statuses = [s for s in pod.get("status", {}).get("containerStatuses", []) if s.get("name") == container]
        containers = [c for c in pod.get("spec", {}).get("containers", []) if c.get("name") == container]
        if (len(statuses) != 1 or len(containers) != 1 or containers[0].get("imagePullPolicy") != "Never" or
                statuses[0].get("ready") is not True or statuses[0].get("imageID") != expected_image_id):
            raise AdapterError("Exec Pod container is not Ready with expected immutable runtime image.")
        raw = self._call(["--namespace", namespace, "exec", name, "-c", container, "--", *COMMANDS[command]],
                         max_output=4096)
        self._namespace(namespace)
        if pod["metadata"].get("uid") != self.get("pod", name, namespace)["metadata"].get("uid"):
            raise AdapterError("Exec Pod UID changed during operation.")
        return raw.decode("utf-8", errors="strict")
