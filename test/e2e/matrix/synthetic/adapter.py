def _env():
    env = {key: os.environ[key] for key in ("PATH", "HOME", "KUBECONFIG") if key in os.environ}
    env["KUBECTL_KUBERC"] = "false"
    return env


def _bounded(argv, *, payload=None, timeout, max_output):
    """Drain only a capped stdout pipe; stderr discarded, timeout kills group."""
    process = None
    selector = selectors.DefaultSelector()
    output = bytearray()
    try:
        process = subprocess.Popen(argv, stdin=subprocess.PIPE if payload is not None else subprocess.DEVNULL,
                                   stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=_env(),
                                   start_new_session=True)
        selector.register(process.stdout, selectors.EVENT_READ)
        sent = 0
        if payload is not None:
            os.set_blocking(process.stdin.fileno(), False)
            selector.register(process.stdin, selectors.EVENT_WRITE)
        end = time.monotonic() + timeout
        while selector.get_map():
            remaining = end - time.monotonic()
            if remaining <= 0:
                raise AdapterError("Bounded Kubernetes operation timed out.")
            for key, _ in selector.select(remaining):
                if key.fileobj == process.stdin:
                    try:
                        sent += os.write(process.stdin.fileno(), payload[sent:sent + 4096])
                    except BrokenPipeError:
                        raise AdapterError("Kubernetes stdin closed before fixture transfer.") from None
                    if sent == len(payload):
                        selector.unregister(process.stdin)
                        process.stdin.close()
                    continue
                chunk = os.read(key.fileobj.fileno(), min(4096, max_output + 1 - len(output)))
                if chunk:
                    output.extend(chunk)
                    if len(output) > max_output:
                        raise AdapterError("Bounded Kubernetes output exceeded limit.")
                else:
                    selector.unregister(key.fileobj)
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise AdapterError("Bounded Kubernetes operation timed out.")
        if process.wait(timeout=remaining) != 0:
            raise AdapterError("Kubernetes operation failed (details suppressed).")
        return bytes(output)
    except (OSError, ValueError, subprocess.TimeoutExpired, BrokenPipeError):
        raise AdapterError("Bounded Kubernetes operation unavailable or failed.") from None
    finally:
        selector.close()
        if process is not None:
            # Kill an isolated process group even if kubectl exited but a
            # descendant inherited stdout and kept the pipe open.
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            try:
                process.wait(timeout=1)
            except subprocess.TimeoutExpired:
                raise AdapterError("Local kubectl child could not be reaped.") from None
            if process.stdin:
                process.stdin.close()
            if process.stdout:
                process.stdout.close()


class FixtureAPI:
    def __init__(self, owner, transport=_bounded):
        if not isinstance(owner, lifecycle.Lifecycle) or owner.deadline is None or owner.closed:
            raise AdapterError("A running, authorized Lifecycle is required.")
        self.owner, self.transport = owner, transport

    def _time(self):
        if self.owner.closed:
            raise AdapterError("Lifecycle is closed.")
        try:
            return self.owner._time(self.owner.deadline)
        except lifecycle.LifecycleError:
            raise AdapterError("Final-gate total deadline exceeded.") from None

    def _namespace(self, name):
        if name not in self.owner.names or name not in self.owner.owned:
            raise AdapterError("Namespace is not confirmed owned by this Lifecycle.")
        try:
            observed = self.owner.api.get(name, timeout=self._time())
            self.owner._record(name, observed)
        except (lifecycle.LifecycleError, KeyError, TypeError, AttributeError):
            raise AdapterError("Namespace UID/ownership recheck failed.") from None
        if self.owner.owned[name] != observed["metadata"]["uid"]:
            raise AdapterError("Namespace UID changed.")
        return name

    def _call(self, args, *, payload=None, max_output=262144):
        timeout = self._time()
        argv = ["kubectl", "--context", CONTEXT, "--request-timeout=10s", *args]
        try:
            result = self.transport(argv, payload=payload, timeout=timeout, max_output=max_output)
            if not isinstance(result, bytes) or len(result) > max_output:
                raise AdapterError("Kubernetes output violated limit or type contract.")
            if self.owner.clock() >= self.owner.deadline:
                raise AdapterError("Final-gate total deadline exceeded.")
            return result
        except (KeyboardInterrupt, SystemExit, lifecycle.Interrupted):
            raise
        except BaseException:
            raise AdapterError("Kubernetes transport failed (details suppressed).") from None

    @staticmethod
    def _name(kind, name):
        allowed = RESOURCES.get(kind)
        if ((allowed is None and kind not in RESOURCES) or not isinstance(name, str) or
                (allowed is not None and name not in allowed) or
                (allowed is None and (not GENERATED.fullmatch(name) or ".." in name))):
            raise AdapterError("Resource kind or name not allowlisted.")

    def get(self, kind, name, namespace):
        self._name(kind, name)
        self._namespace(namespace)
        raw = self._call(["get", kind, name, "--namespace", namespace, "-o", "json"])
        try:
            obj = json.loads(raw)
            if obj.get("metadata", {}).get("name") != name or obj["metadata"].get("namespace") != namespace:
                raise ValueError()
            return obj
        except (ValueError, KeyError, AttributeError, TypeError):
            raise AdapterError("Kubernetes object identity or JSON malformed.") from None

    def create(self, obj):
        """Complete allowlisted fixture JSON via stdin; never log/return body."""
        try:
            kind, meta = obj["kind"], obj["metadata"]
            name, namespace = meta["name"], meta["namespace"]
            if kind not in CREATE or name not in FIXTURE[kind] or type(obj) is not dict:
                raise ValueError()
            if namespace != (self.owner.names[1] if kind == "EgressPolicy" or
                             kind == "Pod" and name == "synthetic-client" else self.owner.names[0]):
                raise ValueError()
            if kind == "Secret":
                keys = {"ca.crt", "server.crt", "server.key", "server.conf"} if name == "synthetic-server" else {"client.ovpn"}
                if (obj.get("apiVersion") != "v1" or obj.get("type") != "Opaque" or
                        set(obj.get("data", {})) != keys or
                        set(obj) != {"apiVersion", "kind", "metadata", "type", "data"} or
                        set(meta) != {"name", "namespace"}):
                    raise ValueError()
            self._namespace(namespace)
            payload = json.dumps(obj, separators=(",", ":"), allow_nan=False).encode()
            if len(payload) > 65536:
                raise ValueError()
        except (KeyError, TypeError, ValueError, AttributeError):
            raise AdapterError("Fixture kind, namespace or payload not allowlisted.") from None
        # Suppress kubectl output entirely; response is not needed and may carry
        # bytes from admission or a misbehaving server. Recheck namespace after.
        self._call(["create", "-f", "-", "-o", "name"], payload=payload, max_output=1024)
        self._namespace(namespace)

    def pod_image_id(self, namespace, name, container, uid):
        if (name, container, namespace) not in {
                ("synthetic-client", "client", self.owner.names[1]),
                ("synthetic-vpn", "server", self.owner.names[0])}:
            raise AdapterError("Pod image target not allowlisted.")
        if not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Pod UID required for image check.")
        pod = self.get("pod", name, namespace)
        if pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp"):
            raise AdapterError("Pod UID changed or deletion started.")
        statuses = [s for s in pod.get("status", {}).get("containerStatuses", []) if s.get("name") == container]
        if len(statuses) != 1 or statuses[0].get("ready") is not True:
            raise AdapterError("Pod container not Ready.")
        image_id = statuses[0].get("imageID")
        if not isinstance(image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", image_id):
            raise AdapterError("Pod runtime image ID malformed or mutable.")
        return image_id

    def server_session(self, namespace, uid, *, expected_image_id):
        """Only sanitized status reader in exact server Pod; never cat/raw logs.

        Caller MUST treat JSON as private transient evidence, never persist it.
        Like kubectl exec generally, there is no server-side Pod UID compare;
        a replacement between precheck and exec remains a hard full-gate block.
        """
        if namespace != self.owner.names[0] or not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Server session namespace or Pod UID invalid.")
        if not isinstance(expected_image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", expected_image_id):
            raise AdapterError("Expected immutable server runtime image required.")
        self._namespace(namespace)
        pod = self.get("pod", "synthetic-vpn", namespace)
        if (pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp") or
                not pod.get("spec", {}).get("nodeName")):
            raise AdapterError("Server Pod UID, scheduling or deletion invalid.")
        spec = [c for c in pod.get("spec", {}).get("containers", []) if c.get("name") == "server"]
        status = [c for c in pod.get("status", {}).get("containerStatuses", []) if c.get("name") == "server"]
        if (len(spec) != 1 or len(status) != 1 or spec[0].get("imagePullPolicy") != "Never" or
                status[0].get("ready") is not True or status[0].get("imageID") != expected_image_id):
            raise AdapterError("Server container not Ready with expected immutable runtime image.")
        raw = self._call(["--namespace", namespace, "exec", "synthetic-vpn", "-c", "server", "--",
                          *SERVER_COMMAND], max_output=384)
        self._namespace(namespace)
        if pod["metadata"].get("uid") != self.get("pod", "synthetic-vpn", namespace)["metadata"].get("uid"):
            raise AdapterError("Server Pod UID changed during session read.")
        try:
            session = json.loads(raw)
            if (not isinstance(session, dict) or
                    set(session) != {"cn", "virtualIPv4", "received", "sent", "connected", "peer", "cipher"} or
                    session.get("cn") != "synthetic-client" or session.get("cipher") not in {"AES-256-GCM", "AES-128-GCM"} or
                    any(type(session.get(key)) is not int or session[key] < 0 for key in ("received", "sent", "connected", "peer")) or
                    not isinstance(session.get("virtualIPv4"), str) or
                    not re.fullmatch(r"10\.88\.0\.[0-9]{1,3}", session["virtualIPv4"])):
                raise ValueError()
            return session
        except (ValueError, UnicodeError, TypeError, AttributeError):
            raise AdapterError("Sanitized server session output malformed.") from None

    def exec(self, namespace, name, uid, container, command, *, expected_image_id):
        if (name, container) != ("synthetic-client", "client") or namespace != self.owner.names[1]:
            raise AdapterError("Exec Pod/container/namespace not allowlisted.")
        if command not in COMMANDS or not isinstance(uid, str) or not UID.fullmatch(uid):
            raise AdapterError("Exec command or Pod UID not allowlisted.")
        if not isinstance(expected_image_id, str) or not re.fullmatch(
                r"(?:[A-Za-z0-9_.-]+://)?sha256:[a-fA-F0-9]{64}", expected_image_id):
            raise AdapterError("Expected immutable runtime image ID required before exec.")
        pod = self.get("pod", name, namespace)
        if (pod["metadata"].get("uid") != uid or pod["metadata"].get("deletionTimestamp") or
                not pod.get("spec", {}).get("nodeName")):
            raise AdapterError("Exec Pod UID changed, unscheduled or deletion started.")
        statuses = [s for s in pod.get("status", {}).get("containerStatuses", []) if s.get("name") == container]
        containers = [c for c in pod.get("spec", {}).get("containers", []) if c.get("name") == container]
        if (len(statuses) != 1 or len(containers) != 1 or containers[0].get("imagePullPolicy") != "Never" or
                statuses[0].get("ready") is not True or statuses[0].get("imageID") != expected_image_id):
            raise AdapterError("Exec Pod container is not Ready with expected immutable runtime image.")
        raw = self._call(["--namespace", namespace, "exec", name, "-c", container, "--", *COMMANDS[command]],
                         max_output=4096)
        self._namespace(namespace)
        if pod["metadata"].get("uid") != self.get("pod", name, namespace)["metadata"].get("uid"):
            raise AdapterError("Exec Pod UID changed during operation.")
        return raw.decode("utf-8", errors="strict")
